void Bridge_GetPixel(int x, int y, uint8_t *r, uint8_t *g, uint8_t *b)
{
    if (x < 0 || x >= 128 || y < 0 || y >= 32) {
        *r = *g = *b = 0;
        return;
    }

    uint16_t v = img_128x32[y][x];

    uint8_t r4 = (v >> 8) & 0x0F;
    uint8_t g4 = (v >> 4) & 0x0F;
    uint8_t b4 = (v >> 0) & 0x0F;

    *r = r4;
    *g = g4;
    *b = b4;

    Traffic_OverlayPixel(x,y,r,g,b);

}
