void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin)
{
    uint32_t now = HAL_GetTick();

    if (GPIO_Pin == GPIO_PIN_0) {
        // 수동 버튼 (PB0)
        static uint32_t last_manual = 0;
        if (now - last_manual < 150) return;  // 디바운스
        last_manual = now;

        Fireworks_TriggerSpawn();
    }
    else if (GPIO_Pin == GPIO_PIN_4) {
        // 자동 모드 버튼 (PB4)
        static uint32_t last_auto = 0;
        if (now - last_auto < 200) return;    // 디바운스
        last_auto = now;

        Fireworks_ToggleAuto();
    }
}


